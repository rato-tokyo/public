def check():
    print('Python:', sys.version.split()[0], '(3.12+ required)')
    for name in ('cryptography', 'numpy', 'cv2'):
        print(name + ':', 'available' if importlib.util.find_spec(name) else 'missing')
    if os.name != 'nt':
        print('Windows required'); return 1
    env = {k:v for k,v in os.environ.items() if k.casefold() != 'psmodulepath'}
    try:
        p = subprocess.run(['powershell.exe', '-NoProfile', '-NonInteractive', '-Command',
            'Get-Command Get-Acl -ErrorAction Stop | Out-Null; Get-ExecutionPolicy'],
            env=env, capture_output=True, text=True, timeout=10)
        print('Windows PowerShell:', 'available' if p.returncode == 0 else 'check failed')
        print('Execution policy:', p.stdout.strip() or 'unknown')
    except (OSError, subprocess.TimeoutExpired) as e:
        print('PowerShell check failed:', type(e).__name__)
    print('No capture, display, or shared folder was opened.')
    return 0

def unpack():
    if os.name != 'nt' or sys.version_info < (3,12):
        raise RuntimeError('Windows and Python 3.12+ required')
    data = base64.b64decode(PAYLOAD, validate=True)
    if hashlib.sha256(data).hexdigest() != PAYLOAD_SHA256:
        raise RuntimeError('Embedded candidate hash mismatch')
    local = os.environ.get('LOCALAPPDATA')
    if not local: raise RuntimeError('LOCALAPPDATA unavailable')
    root = pathlib.Path(local) / 'transceiver-candidate' / PAYLOAD_SHA256
    # Reject redirected existing ancestors before creating any files.
    for ancestor in reversed((root, *root.parents)):
        if ancestor.exists() and (ancestor.is_symlink() or getattr(ancestor.lstat(), 'st_file_attributes', 0) & 0x400):
            raise RuntimeError('Reparse point in extraction path')
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        manifest = json.loads(z.read('transceiver/candidate-manifest.json'))
        files = manifest['files']
        for name, metadata in files.items():
            rel = pathlib.PurePosixPath(name)
            if rel.is_absolute() or '..' in rel.parts or not rel.parts:
                raise RuntimeError('Unsafe embedded file path')
            content = z.read('transceiver/' + name)
            if len(content) != metadata['size'] or hashlib.sha256(content).hexdigest() != metadata['sha256']:
                raise RuntimeError('Embedded file hash mismatch: ' + name)
            target = root.joinpath(*rel.parts)
            # Never follow an existing link or replace a file.
            for parent in (root, *[root.joinpath(*rel.parts[:i]) for i in range(1, len(rel.parts))]):
                if parent.exists() and (parent.is_symlink() or getattr(parent.lstat(), 'st_file_attributes', 0) & 0x400):
                    raise RuntimeError('Reparse point in extraction path')
                parent.mkdir(exist_ok=True, parents=True)
            try:
                with target.open('xb') as f: f.write(content)
            except FileExistsError:
                if target.is_symlink() or getattr(target.lstat(), 'st_file_attributes', 0) & 0x400 or target.read_bytes() != content:
                    raise RuntimeError('Existing candidate file differs: ' + str(target))
    return root

def test_agent(base):
    import getpass
    from transceiver.cli import local_path, main
    missing = [m for m in ('cryptography', 'numpy', 'cv2') if importlib.util.find_spec(m) is None]
    if missing: raise RuntimeError('Missing Python packages: ' + ', '.join(missing))
    from transceiver.link.vendor.hardware import configure_dpi, active_monitors, choose_external_monitor, require_opencv_gui
    require_opencv_gui()
    configure_dpi()
    monitor = choose_external_monitor(active_monitors())
    print('External display:', monitor['device'], monitor['rect'], flush=True)
    print('Enter the DirectShow index of the USB HDMI capture device.', flush=True)
    value = input('Capture index: ').strip()
    if not value.isascii() or not value.isdigit() or int(value) > 99:
        raise ValueError('Capture index must be an integer from 0 to 99')
    password = getpass.getpass('Same password as main PC (input hidden): ')
    if not password or '\n' in password or '\r' in password:
        raise ValueError('A nonempty one-line password is required')
    if password != getpass.getpass('Repeat password: '):
        raise ValueError('Passwords do not match')
    root = local_path(str(pathlib.Path(os.environ['LOCALAPPDATA']) / 'transceiver-hardware-test'))
    root.mkdir(parents=True, exist_ok=True)
    key = root / 'key.txt'
    try:
        with key.open('x', encoding='utf-8') as f: f.write(password)
    except FileExistsError:
        local_path(str(key))
        if key.read_text(encoding='utf-8').rstrip('\r\n') != password:
            raise RuntimeError('Existing test key differs; it was not replaced')
    fixture = local_path(str(root / 'fixture'))
    fixture.mkdir(exist_ok=True)
    sample = fixture / 'transceiver-test.txt'
    try:
        with sample.open('x', encoding='utf-8', newline='\n') as f: f.write('Transceiver hardware test.\n')
    except FileExistsError:
        local_path(str(sample))
        if sample.read_bytes() != b'Transceiver hardware test.\n':
            raise RuntimeError('Existing test file differs; it was not replaced')
    config = local_path(str(root / 'agent-config.json'))
    settings = {'key_path': str(key), 'capture_device': int(value), 'monitor_device': monitor['device']}
    encoded = json.dumps(settings, ensure_ascii=False, indent=2)
    try:
        with config.open('x', encoding='utf-8') as f: f.write(encoded)
    except FileExistsError:
        if json.loads(config.read_text(encoding='utf-8')) != settings:
            raise RuntimeError('Existing test configuration differs; it was not replaced')
    print('Test source:', sample, flush=True)
    print('Starting agent. No shared folder is in scope. Keep this window open.', flush=True)
    sys.argv = [sys.argv[0], '--state-dir', str(root / 'state'), 'run', '--role', 'agent',
                '--transport', 'pixel', '--config', str(config), '--allow-root', str(fixture),
                '--output', str(root / 'output')]
    return main(base)

if __name__ == '__main__':
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, 'reconfigure'): stream.reconfigure(encoding='utf-8', errors='backslashreplace')
    if len(sys.argv) == 1 or sys.argv[1] == '--check':
        raise SystemExit(check())
    try:
        base = unpack()
        sys.path.insert(0, str(base / 'src'))
        if sys.argv[1] == '--test-agent':
            raise SystemExit(test_agent(base))
        from transceiver.cli import main
        raise SystemExit(main(base))
    except (OSError, ValueError, RuntimeError) as exc:
        print('ERROR:', exc, file=sys.stderr); raise SystemExit(2)
