def safe_local_path(value):
    # Inspect drive type before touching a path: no UNC or mapped network I/O.
    import ctypes
    from ctypes import wintypes
    raw = str(value).replace('/', '\\')
    parsed = pathlib.PureWindowsPath(raw)
    if raw.startswith('\\\\') or not parsed.is_absolute() or len(parsed.drive) != 2:
        raise ValueError('A local absolute drive path is required')
    if any(part in ('.', '..') for part in parsed.parts):
        raise ValueError('Path traversal is forbidden')
    kernel = ctypes.WinDLL('kernel32', use_last_error=True)
    kernel.GetDriveTypeW.argtypes = [wintypes.LPCWSTR]
    kernel.GetDriveTypeW.restype = wintypes.UINT
    if kernel.GetDriveTypeW(parsed.anchor) not in (2, 3, 5, 6):
        raise ValueError('Mapped network or unavailable drives are forbidden')
    kernel.GetFileAttributesW.argtypes = [wintypes.LPCWSTR]
    kernel.GetFileAttributesW.restype = wintypes.DWORD
    current = pathlib.Path(parsed.anchor)
    for component in ('', *parsed.parts[1:]):
        if component:
            if component.endswith((' ', '.')) or any(ord(c) < 32 or c in '<>:"|?*' for c in component):
                raise ValueError('Unsafe local path component')
            current = current / component
        attributes = kernel.GetFileAttributesW(str(current))
        if attributes == 0xFFFFFFFF:
            error = ctypes.get_last_error()
            if error in (2, 3): break
            raise ctypes.WinError(error)
        if attributes & 0x400:
            raise ValueError('Reparse components forbidden in local data paths')
    return pathlib.Path(raw).absolute()

def check():
    good = sys.version_info >= (3, 12)
    print('Python:', sys.version.split()[0], '(3.12+ required)')
    for name in ('cryptography', 'numpy', 'cv2'):
        try:
            module = importlib.import_module(name)
            print(name + ': available')
            if name == 'cv2':
                info = module.getBuildInformation()
                gui = next((line.partition(':')[2].strip() for line in info.splitlines()
                            if line.strip().startswith('GUI:')), '')
                if gui.upper() in ('', 'NONE', 'NO'):
                    print('OpenCV GUI: missing'); good = False
                else: print('OpenCV GUI:', gui)
        except (ImportError, OSError, AttributeError) as error:
            print(name + ': unavailable (' + type(error).__name__ + ')'); good = False
    if os.name != 'nt':
        print('Windows required'); return 1
    env = {k:v for k,v in os.environ.items() if k.casefold() != 'psmodulepath'}
    try:
        p = subprocess.run(['powershell.exe', '-NoProfile', '-NonInteractive', '-Command',
            '$ErrorActionPreference="Stop"; Get-Command Get-Acl -ErrorAction Stop | Out-Null; $PSVersionTable.PSVersion.ToString(); Get-ExecutionPolicy'],
            env=env, capture_output=True, text=True, timeout=10)
        lines = p.stdout.splitlines()
        print('Windows PowerShell:', lines[0] if p.returncode == 0 and lines else 'check failed')
        print('Execution policy:', lines[1] if p.returncode == 0 and len(lines) > 1 else 'unknown')
        if p.returncode != 0 or len(lines) < 2: good = False
        else:
            try:
                version = tuple(int(x) for x in lines[0].split('.')[:2])
                if version < (5, 1) or version >= (6, 0):
                    print('Windows PowerShell 5.1 required'); good = False
            except ValueError: good = False
        # A policy label alone cannot prove .ps1 execution. Test a new local,
        # harmless script under the same launch flags as the worker.
        temp = safe_local_path(tempfile.gettempdir())
        with tempfile.TemporaryDirectory(prefix='transceiver-check-', dir=temp) as directory:
            script = pathlib.Path(directory) / 'check.ps1'
            script.write_text("Write-Output 'TRANSCHECK_OK'\n", encoding='utf-8')
            test = subprocess.run(['powershell.exe', '-NoProfile', '-NonInteractive', '-File', str(script)],
                                  env=env, capture_output=True, text=True, timeout=10)
            allowed = test.returncode == 0 and 'TRANSCHECK_OK' in test.stdout
            print('Local .ps1 execution:', 'available' if allowed else 'failed')
            if not allowed: good = False
    except (OSError, ValueError, RuntimeError, subprocess.TimeoutExpired) as e:
        print('PowerShell check failed:', type(e).__name__); good = False
    print('No capture, display, or shared folder was opened.')
    print('Preflight:', 'PASS' if good else 'FAIL')
    return 0 if good else 1

def ensure_named_streams_supported(path):
    # An absent ADS cannot establish that no mark exists on a filesystem that
    # cannot represent ADS at all. Fail closed in that case.
    import ctypes
    from ctypes import wintypes
    kernel = ctypes.WinDLL('kernel32', use_last_error=True)
    kernel.GetVolumePathNameW.argtypes = [wintypes.LPCWSTR, wintypes.LPWSTR, wintypes.DWORD]
    kernel.GetVolumePathNameW.restype = wintypes.BOOL
    volume = ctypes.create_unicode_buffer(32768)
    if not kernel.GetVolumePathNameW(str(path), volume, len(volume)):
        raise RuntimeError('Cannot verify filesystem origin support; ask your administrator')
    kernel.GetVolumeInformationW.argtypes = [wintypes.LPCWSTR, wintypes.LPWSTR, wintypes.DWORD,
        ctypes.POINTER(wintypes.DWORD), ctypes.POINTER(wintypes.DWORD), ctypes.POINTER(wintypes.DWORD),
        wintypes.LPWSTR, wintypes.DWORD]
    kernel.GetVolumeInformationW.restype = wintypes.BOOL
    flags = wintypes.DWORD()
    if not kernel.GetVolumeInformationW(volume.value, None, 0, None, None, ctypes.byref(flags), None, 0):
        raise RuntimeError('Cannot verify filesystem origin support; ask your administrator')
    if not flags.value & 0x00040000:  # FILE_NAMED_STREAMS
        raise RuntimeError('Filesystem cannot represent downloaded file origin marks; ask your administrator')

def verify_source_zone(source):
    # Do not erase Internet-origin evidence by extracting an unmarked ps1.
    # A marked launcher needs a policy-compliant administrator-approved route.
    script = safe_local_path(str(pathlib.Path(source).absolute()))
    ensure_named_streams_supported(script)
    try:
        with open(str(script) + ':Zone.Identifier', 'rb') as stream:
            data = stream.read(8193)
    except FileNotFoundError:
        return
    except OSError as exc:
        raise RuntimeError('Cannot verify downloaded file origin; ask your administrator') from exc
    if len(data) > 8192:
        raise RuntimeError('Downloaded file origin is too large to verify')
    match = re.search(rb'(?im)^\s*ZoneId\s*=\s*(\d+)\s*$', data)
    if not match:
        raise RuntimeError('Downloaded file origin is invalid; ask your administrator')
    if int(match.group(1)) >= 3:
        raise RuntimeError('Internet-marked launcher cannot extract an unmarked PowerShell script; use an administrator-approved, policy-compliant method')

def unpack():
    if os.name != 'nt' or sys.version_info < (3,12):
        raise RuntimeError('Windows and Python 3.12+ required')
    verify_source_zone(sys.argv[0])
    data = base64.b64decode(PAYLOAD, validate=True)
    if hashlib.sha256(data).hexdigest() != PAYLOAD_SHA256:
        raise RuntimeError('Embedded candidate hash mismatch')
    local = os.environ.get('LOCALAPPDATA')
    if not local: raise RuntimeError('LOCALAPPDATA unavailable')
    root = safe_local_path(str(pathlib.Path(local) / 'transceiver-candidate' / PAYLOAD_SHA256))
    # Reject redirected existing ancestors before creating any files.
    for ancestor in reversed((root, *root.parents)):
        if ancestor.exists() and (ancestor.is_symlink() or getattr(ancestor.lstat(), 'st_file_attributes', 0) & 0x400):
            raise RuntimeError('Reparse point in extraction path')
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        manifest = json.loads(z.read('transceiver/candidate-manifest.json'))
        files = manifest['files']
        for name, metadata in files.items():
            rel = pathlib.PurePosixPath(name)
            if rel.is_absolute() or '..' in rel.parts or not rel.parts:
                raise RuntimeError('Unsafe embedded file path')
            content = z.read('transceiver/' + name)
            if len(content) != metadata['size'] or hashlib.sha256(content).hexdigest() != metadata['sha256']:
                raise RuntimeError('Embedded file hash mismatch: ' + name)
            target = root.joinpath(*rel.parts)
            # Never follow an existing link or replace a file.
            for parent in (root, *[root.joinpath(*rel.parts[:i]) for i in range(1, len(rel.parts))]):
                if parent.exists() and (parent.is_symlink() or getattr(parent.lstat(), 'st_file_attributes', 0) & 0x400):
                    raise RuntimeError('Reparse point in extraction path')
                parent.mkdir(exist_ok=True, parents=True)
            try:
                with target.open('xb') as f: f.write(content)
            except FileExistsError:
                if target.is_symlink() or getattr(target.lstat(), 'st_file_attributes', 0) & 0x400 or target.read_bytes() != content:
                    raise RuntimeError('Existing candidate file differs: ' + str(target))
    return root

def test_agent(base):
    import getpass
    from transceiver import cli
    local_path = cli.local_path
    missing = [m for m in ('cryptography', 'numpy', 'cv2') if importlib.util.find_spec(m) is None]
    if missing: raise RuntimeError('Missing Python packages: ' + ', '.join(missing))
    from transceiver.link.vendor.hardware import configure_dpi, active_monitors, require_opencv_gui
    from transceiver.capture_inventory import list_capture_devices
    require_opencv_gui()
    configure_dpi()
    print('Displays:', active_monitors(), flush=True)
    devices, error = list_capture_devices()
    if error:
        print('Capture device enumeration unavailable:', error, flush=True)
        print('Use an independently verified capture index.', flush=True)
    elif not devices:
        raise RuntimeError('No DirectShow capture device is available')
    else:
        print('Available capture devices:', flush=True)
        for item in devices:
            print('  ' + str(item['index']) + ': ' + item['name'], flush=True)
    print('Enter the DirectShow index of the USB HDMI capture device.', flush=True)
    value = input('Capture index: ').strip()
    if not value.isascii() or not value.isdigit() or int(value) > 99:
        raise ValueError('Capture index must be an integer from 0 to 99')
    if not error and not any(item['index'] == int(value) for item in devices):
        raise ValueError('Capture index is not in the current device list')
    password = getpass.getpass('Same password as main PC (input hidden): ')
    if not password or '\n' in password or '\r' in password:
        raise ValueError('A nonempty one-line password is required')
    if password != getpass.getpass('Repeat password: '):
        raise ValueError('Passwords do not match')
    root = local_path(str(pathlib.Path(os.environ['LOCALAPPDATA']) / 'transceiver-hardware-test'))
    root.mkdir(parents=True, exist_ok=True)
    fixture = local_path(str(root / 'fixture'))
    fixture.mkdir(exist_ok=True)
    sample = fixture / 'transceiver-test.txt'
    try:
        with sample.open('x', encoding='utf-8', newline='\n') as f: f.write('Transceiver hardware test.\n')
    except FileExistsError:
        local_path(str(sample))
        if sample.read_bytes() != b'Transceiver hardware test.\n':
            raise RuntimeError('Existing test file differs; it was not replaced')
    # Keep earlier configurations intact while allowing a capture index to
    # change after reconnecting the device; never replace an existing file.
    # The transport validates the display when it starts. Do not guess a
    # display here or prevent future coordinated capture/display startup.
    settings = {'capture_device': int(value), 'monitor_device': None,
                'monitor_wait_seconds': 3600, 'handshake_timeout_seconds': 3600}
    encoded = json.dumps(settings, ensure_ascii=False, indent=2)
    # Retain previous settings if defaults evolve, without silently reusing or
    # overwriting an earlier capture configuration.
    config_id = hashlib.sha256(encoded.encode('utf-8')).hexdigest()[:16]
    config = local_path(str(root / ('agent-config-' + value + '-' + config_id + '.json')))
    try:
        with config.open('x', encoding='utf-8') as f: f.write(encoded)
    except FileExistsError:
        if json.loads(config.read_text(encoding='utf-8')) != settings:
            raise RuntimeError('Existing test configuration differs; it was not replaced')
    print('TEST SOURCE PATH (give this path to the main PC):', sample, flush=True)
    print('Starting agent. No shared folder is in scope. Keep this window open.', flush=True)
    sys.argv = [sys.argv[0], '--state-dir', str(root / 'state'), 'run', '--role', 'agent',
                '--transport', 'pixel', '--config', str(config), '--allow-root', str(fixture),
                '--output', str(root / 'output')]
    # No key file or plaintext password is written: provide the in-memory
    # password only for this service's configuration load. Other JSON reads
    # (jobs, state) retain their ordinary behavior. Existing keys are untouched.
    normal_read_json = cli.read_json
    def read_session_config(path):
        data = normal_read_json(path)
        if pathlib.Path(path) == config:
            data = dict(data, password=password)
        return data
    cli.read_json = read_session_config
    try:
        return cli.main(base)
    finally:
        cli.read_json = normal_read_json

